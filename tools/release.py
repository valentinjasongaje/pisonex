"""
Pisonex release tool — one place to bump the version and build installers.

The ONLY place a version number is typed by hand is  pisonex/VERSION.
Everything else either reads that file at build time or is regenerated from it:

    reads VERSION directly            regenerated by `sync` / `bump`
    ───────────────────────────        ───────────────────────────────────
    client/Directory.Build.props      server*/version.py  (→ /health, dashboard
      (PisoNetClient.exe, pnxsystem)    footer, FastAPI, pisonex.com telemetry)
    build/PisoNetSetup.iss            docs/api.md
    build/PisoNetClientSetup.iss      pisonex-web admin docs pages (if present)
    build/build*.bat                  deploy/make-release.sh reads it on the Pi

Commands — run from the pisonex REPO folder (www/pisonex/pisonex). From the
workspace folder (www/pisonex) use the shortcut instead: `release status`,
`release bump patch`, ... (release.cmd forwards to this script).

    python tools/release.py status              show the version + any drift
    python tools/release.py bump 1.0.5          set an exact version
    python tools/release.py bump patch          1.0.4 -> 1.0.5   (also: minor, major, build)
    python tools/release.py sync                rewrite generated files from VERSION
    python tools/release.py build               test + build BOTH Windows installers
    python tools/release.py build --server      only the server installer
    python tools/release.py build --client      only the client installer
    python tools/release.py build --skip-tests  skip the smoke test gate (not recommended)
    python tools/release.py notes               print release notes since the last tag

A finished build lands in  build/output/v<version>/  with SHA256SUMS.txt and
RELEASE_NOTES.md next to the installers.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent          # pisonex/  (git repo)
WORKSPACE = ROOT.parent                                # holds build/ and pisonex-web/
BUILD = WORKSPACE / "build"
WEB = WORKSPACE / "pisonex-web"
VERSION_FILE = ROOT / "VERSION"
SERVER_VARIANTS = ["server", "server-orangepi", "server-windows"]

_VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(\.\d+)?$")
_V = r"\d+\.\d+\.\d+(?:\.\d+)?"


# ── generated files ───────────────────────────────────────────────────────────
# (path, regex with exactly one group around the version, required?)

def _targets() -> list[tuple[Path, str, bool]]:
    t = [(ROOT / v / "version.py", rf'__version__ = "({_V})"', True) for v in SERVER_VARIANTS]
    t += [
        (ROOT / "docs" / "api.md", rf"\*\*Version:\*\* ({_V})", True),
        (ROOT / "docs" / "api.md", rf'"version": "({_V})"', True),
        (WEB / "src" / "app" / "admin" / "docs" / "api" / "page.tsx", rf"— Version ({_V})", False),
        (WEB / "src" / "app" / "admin" / "docs" / "api" / "page.tsx", rf'"version": "({_V})"', False),
        (WEB / "src" / "app" / "admin" / "docs" / "security" / "page.tsx", rf'version="({_V})"', False),
    ]
    return t


# Places that must NOT contain a hard-coded version any more (regression guard).
_FORBIDDEN = [
    (ROOT / "client" / "PisoNetClient" / "PisoNetClient.vbproj", r"<(Assembly|File)?Version>\d"),
    (BUILD / "PisoNetSetup.iss", r'#define\s+AppVersion\s+"\d'),
    (BUILD / "PisoNetClientSetup.iss", r'#define\s+MyAppVersion\s+"\d'),
] + [
    (ROOT / v / f, r'(version="\d|"version": "\d|"app_version": "\d|class="version">v\d)')
    for v in SERVER_VARIANTS
    for f in ("main.py", "services/license_service.py",
              "dashboard/templates/layout.html", "dashboard/templates/docs_api.html")
]


def _read(p: Path) -> str:
    return p.read_bytes().decode("utf-8")


def _write_keep_newlines(p: Path, text: str, original: str):
    if "\r\n" in original:
        text = text.replace("\r\n", "\n").replace("\n", "\r\n")
    p.write_bytes(text.encode("utf-8"))


def read_version() -> str:
    v = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not _VERSION_RE.match(v):
        sys.exit(f"pisonex/VERSION contains '{v}', expected e.g. 1.0.5 or 1.0.5.1")
    return v


def _rel(p: Path) -> str:
    try:
        return str(p.relative_to(WORKSPACE))
    except ValueError:
        return str(p)


def check(version: str, verbose: bool = True) -> list[str]:
    """Return a list of drift problems (empty = everything in sync)."""
    problems = []
    for path, pattern, required in _targets():
        if not path.exists():
            if required:
                problems.append(f"missing: {_rel(path)}")
            continue
        found = re.findall(pattern, _read(path))
        if not found:
            if required:
                problems.append(f"{_rel(path)}: version marker not found ({pattern})")
            continue
        bad = sorted({f for f in found if f != version})
        if bad:
            problems.append(f"{_rel(path)}: has {', '.join(bad)} (expected {version})")
        elif verbose:
            print(f"  ok     {_rel(path)}")
    for path, pattern in _FORBIDDEN:
        if path.exists() and re.search(pattern, _read(path)):
            problems.append(f"{_rel(path)}: hard-coded version found — it should come from VERSION")
    return problems


def sync(version: str) -> int:
    changed = 0
    for path, pattern, required in _targets():
        if not path.exists():
            if required and path.name == "version.py":
                path.write_text(_version_py(version), encoding="utf-8", newline="\n")
                print(f"  created {_rel(path)}")
                changed += 1
            continue
        if path.name == "version.py":
            original = _read(path)
            new = _version_py(version)
        else:
            original = _read(path)
            new = re.sub(pattern, lambda m: m.group(0).replace(m.group(1), version), original)
        if new.replace("\r\n", "\n") != original.replace("\r\n", "\n"):
            _write_keep_newlines(path, new, original)
            print(f"  updated {_rel(path)}")
            changed += 1
    return changed


def _version_py(version: str) -> str:
    return (
        '"""Pisonex version — GENERATED by tools/release.py, do not edit by hand.\n\n'
        "The single source of truth is pisonex/VERSION. Change it with:\n"
        "    python tools/release.py bump <new-version>\n"
        '"""\n\n'
        f'__version__ = "{version}"\n'
    )


def next_version(current: str, part: str) -> str:
    nums = [int(x) for x in current.split(".")]
    while len(nums) < 3:
        nums.append(0)
    if part == "major":
        return f"{nums[0] + 1}.0.0"
    if part == "minor":
        return f"{nums[0]}.{nums[1] + 1}.0"
    if part == "patch":
        return f"{nums[0]}.{nums[1]}.{nums[2] + 1}"
    if part == "build":
        build = nums[3] + 1 if len(nums) > 3 else 1
        return f"{nums[0]}.{nums[1]}.{nums[2]}.{build}"
    raise ValueError(part)


# ── git helpers ───────────────────────────────────────────────────────────────

def _git(*args: str, cwd: Path = ROOT) -> str:
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def release_notes(version: str) -> str:
    last_tag = _git("describe", "--tags", "--abbrev=0", "--match", "v*")
    rng = f"{last_tag}..HEAD" if last_tag else "-30"
    log = _git("log", "--no-merges", "--format=- %s (%h)", *([rng] if last_tag else ["-30"]))
    head = _git("rev-parse", "--short", "HEAD") or "unknown"
    dirty = bool(_git("status", "--porcelain"))
    lines = [
        f"# Pisonex v{version}",
        "",
        f"Built {datetime.now():%Y-%m-%d %H:%M} from commit {head}"
        + (" **with uncommitted changes**" if dirty else ""),
        "",
        f"## Changes since {last_tag}" if last_tag else "## Recent changes (no previous v* tag found)",
        "",
        log or "- (no commits found)",
        "",
    ]
    return "\n".join(lines)


# ── build ─────────────────────────────────────────────────────────────────────

def _run_bat(bat: Path) -> bool:
    env = dict(os.environ, PISONEX_NO_PAUSE="1")
    print(f"\n>>> {bat.name}")
    return subprocess.run(["cmd", "/c", str(bat)], cwd=bat.parent, env=env).returncode == 0


def build(version: str, server: bool, client: bool, skip_tests: bool, allow_dirty: bool) -> int:
    if sys.platform != "win32":
        sys.exit("Windows installers can only be built on Windows.")

    problems = check(version, verbose=False)
    if problems:
        print("Version drift — run `python tools/release.py sync` first:")
        for p in problems:
            print("  -", p)
        return 1

    if _git("status", "--porcelain") and not allow_dirty:
        print("WARNING: the pisonex repo has uncommitted changes — the installer will")
        print("         contain code that isn't in git. Commit first, or pass --allow-dirty.")
        return 1

    if not skip_tests:
        variants = ["server-windows"] if server and not client else SERVER_VARIANTS
        print(f"\n>>> smoke tests ({', '.join(variants)})")
        rc = subprocess.run([sys.executable, str(ROOT / "tools" / "smoke_test.py"), *variants]).returncode
        if rc != 0:
            print("\nSmoke tests failed — not building. (Use --skip-tests to override.)")
            return 1

    out_dir = BUILD / "output"
    release_dir = out_dir / f"v{version}"
    release_dir.mkdir(parents=True, exist_ok=True)

    produced: list[Path] = []
    jobs = []
    if server:
        jobs.append((BUILD / "build.bat", f"PisonexServerSetup-v{version}.exe"))
    if client:
        jobs.append((BUILD / "build-client.bat", f"PisonexClientSetup-v{version}.exe"))

    for bat, name in jobs:
        built = out_dir / name
        if built.exists():
            built.unlink()          # never ship a stale file from a previous run
        if not _run_bat(bat) or not built.exists():
            print(f"\nBUILD FAILED: {bat.name} did not produce {name}")
            return 1
        dest = release_dir / name
        shutil.move(str(built), dest)
        produced.append(dest)

    sums = release_dir / "SHA256SUMS.txt"
    existing = {}
    if sums.exists():
        for line in sums.read_text(encoding="utf-8").splitlines():
            if "  " in line:
                h, n = line.split("  ", 1)
                existing[n] = h
    for p in produced:
        existing[p.name] = hashlib.sha256(p.read_bytes()).hexdigest()
    sums.write_text("".join(f"{h}  {n}\n" for n, h in sorted(existing.items())), encoding="utf-8")
    (release_dir / "RELEASE_NOTES.md").write_text(release_notes(version), encoding="utf-8")

    print("\n" + "=" * 60)
    print(f" Pisonex v{version} — build complete")
    print("=" * 60)
    for p in produced:
        print(f"  {p.name:42s} {p.stat().st_size / 1_048_576:7.1f} MB")
    print(f"\n  Folder: {release_dir}")
    print("\nNext steps:")
    print(f"  1. Install on a test PC / upgrade over the previous version and check it starts.")
    print(f"  2. Tag the release:  git -C \"{ROOT}\" tag -a v{version} -m \"Pisonex v{version}\"")
    print(f"                        git -C \"{ROOT}\" push origin v{version}")
    print("  3. Upload the installers to the Google Drive folders linked on pisonex.com/download.")
    print("  4. Orange Pi:  cd /opt/pisonex/server-orangepi && git pull && sudo systemctl restart pisonex")
    return 0


# ── CLI ───────────────────────────────────────────────────────────────────────

def main() -> int:
    # Windows consoles default to cp1252, which can't print the dashes/peso signs used here.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status", help="show the version and any drift")
    b = sub.add_parser("bump", help="set a new version and sync every file")
    b.add_argument("version", help="exact version (1.0.5) or one of: major, minor, patch, build")
    sub.add_parser("sync", help="rewrite generated files from VERSION")
    bl = sub.add_parser("build", help="smoke test + build Windows installers")
    bl.add_argument("--server", action="store_true", help="only the server installer")
    bl.add_argument("--client", action="store_true", help="only the client installer")
    bl.add_argument("--skip-tests", action="store_true")
    bl.add_argument("--allow-dirty", action="store_true", help="build even with uncommitted changes")
    sub.add_parser("notes", help="print release notes since the last v* tag")
    args = ap.parse_args()

    version = read_version()

    if args.cmd == "status":
        print(f"VERSION = {version}\n")
        problems = check(version)
        if problems:
            print("\nDrift found (fix with `python tools/release.py sync`):")
            for p in problems:
                print("  -", p)
            return 1
        print("\nEverything is in sync.")
        return 0

    if args.cmd == "bump":
        new = args.version
        if new in ("major", "minor", "patch", "build"):
            new = next_version(version, new)
        if not _VERSION_RE.match(new):
            sys.exit(f"'{new}' is not a valid version (expected e.g. 1.0.5 or 1.0.5.1)")
        VERSION_FILE.write_text(new + "\n", encoding="utf-8", newline="\n")
        print(f"VERSION: {version} -> {new}")
        sync(new)
        problems = check(new, verbose=False)
        for p in problems:
            print("  ! ", p)
        print(f"\nNext:  review the changes, commit, then build:")
        print(f'  git -C "{ROOT}" commit -am "chore: release v{new}"')
        print(f'  git -C "{ROOT}" push')
        print(f'  python "{Path(__file__).resolve()}" build --server   (or no flag for both installers)')
        return 1 if problems else 0

    if args.cmd == "sync":
        n = sync(version)
        print(f"{n} file(s) updated." if n else "Already in sync.")
        return 1 if check(version, verbose=False) else 0

    if args.cmd == "build":
        both = not args.server and not args.client
        return build(version, args.server or both, args.client or both,
                     args.skip_tests, args.allow_dirty)

    if args.cmd == "notes":
        print(release_notes(version))
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
